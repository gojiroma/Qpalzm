function puny(label){
  if(!label.startsWith('xn--')) return label;
  const s=label.slice(4), base=36, tMin=1, tMax=26, skew=38, damp=700;
  let out=[], i=0, n=128, bias=72, b=s.lastIndexOf('-');
  if(b>0) for(let j=0;j<b;j++) out.push(s.charCodeAt(j));
  const digit=c=>c-48<10?c-22:c-65<26?c-65:c-97<26?c-97:base;
  const adapt=(d,np,first)=>{ d=first?Math.floor(d/damp):d>>1; d+=Math.floor(d/np); let k=0; while(d>((base-tMin)*tMax)>>1){ d=Math.floor(d/(base-tMin)); k+=base; } return k+Math.floor((base-tMin+1)*d/(d+skew)); };
  for(let p=b>0?b+1:0;p<s.length;){
    const old=i; let w=1;
    for(let k=base;;k+=base){
      const d=digit(s.charCodeAt(p++)); if(d>=base) return label;
      i+=d*w; const t=k<=bias?tMin:k>=bias+tMax?tMax:k-bias;
      if(d<t) break; w*=base-t;
    }
    bias=adapt(i-old,out.length+1,old===0); n+=Math.floor(i/(out.length+1)); i%=out.length+1;
    out.splice(i++,0,n);
  }
  return String.fromCodePoint(...out);
}

